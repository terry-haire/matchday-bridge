"""Generates code from the design sheets. Each sheet row becomes one struct/constant entry.

    python tools/gen.py        -> bridge/gen_structs.py, spfl/modules/matchday_gen.lua
"""
from __future__ import annotations

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = os.path.join(ROOT, "sheets")


def load(name):
    return json.load(open(os.path.join(S, name + ".json"), encoding="utf-8"))


def gen_python():
    fm = load("fm_structs")
    attrs = load("fm_attributes")
    pes = load("pes_player_fields")
    rmap = load("ratings_map")
    pos = load("positions_map")
    out = ['"""GENERATED by tools/gen.py from sheets/*.json - edit the sheets, not this file."""', ""]
    structs: dict[str, list] = {}
    for r in fm:
        structs.setdefault(r["struct"], []).append(r)
    for sname, rows in structs.items():
        out.append(f"class {sname}:")
        for r in rows:
            if not r["offset"]:
                out.append(f"    # {r['field'].upper()}: not available - see preflight ({r['id']})")
                continue
            out.append(f"    {r['field'].upper()} = {r['offset']}  # {r['type']}: {r['meaning']}")
        out.append("")
    out.append("FM_ATTRIBUTES = {")
    for r in attrs:
        out.append(f"    {r['name']!r}: {r['offset']},")
    out.append("}")
    out.append("")
    out.append("PES_PLAYER_FIELDS = {  # name: (bit, width, add)")
    for r in pes:
        out.append(f"    {r['name']!r}: ({r['bit']}, {r['width']}, {r['add']}),")
    out.append("}")
    out.append("")
    out.append("PES_LIVE_FIELDS = {  # name: (bit, width) in a live edit-block player record; holds the full value")
    for r in pes:
        out.append(f"    {r['name']!r}: ({r['live_bit']}, {r['live_width']}),")
    out.append("}")
    out.append("")
    spfl: dict[str, list] = {}
    for r in load("spfl_structs"):
        spfl.setdefault(r["struct"], []).append(r)
    for sname, rows in spfl.items():
        out.append(f"class SPFL_{sname}:")
        for r in rows:
            out.append(f"    {r['field'].upper()} = {r['offset']}  # {r['type']}: {r['meaning']}")
        out.append("")
    out.append("RATINGS_MAP = {  # PES ability: [(FM attribute, weight)]")
    for r in rmap:
        terms = ", ".join(f"({k!r}, {v})" for k, v in r["weights"].items())
        out.append(f"    {r['pes_ability']!r}: [{terms}],")
    out.append("}")
    out.append("")
    out.append("FM_POSITION_SLOTS = [  # FM position-rating slot index -> (FM code, PES position)")
    for r in sorted(pos, key=lambda r: r["fm_slot"]):
        out.append(f"    ({r['fm_code']!r}, {r['pes_position']!r}),")
    out.append("]")
    out.append("")
    out.append("SPARE_SLOTS = {  # game: team ids lent to clubs the game cannot pick, in order of use")
    slots: dict[str, list] = {}
    for r in load("spfl_slots"):
        slots.setdefault(r["game"], []).append(r)
    for game, rows in slots.items():
        out.append(f"    {game!r}: [")
        for r in rows:
            out.append(f"        {r['team_id']},  # {r['original_name']}")
        out.append("    ],")
    out.append("}")
    out.append("")
    out.append("GAME_EXES = {  # PE link timestamp of the game exe: (game, edit block owner global: [[global]+0x48])")
    for r in load("game_exes"):
        out.append(f"    {r['pe_timestamp']}: ({r['game']!r}, {r['owner_global']}),  # {r['exe']} {r['version']}")
    out.append("}")
    open(os.path.join(ROOT, "bridge", "gen_structs.py"), "w", encoding="utf-8").write("\n".join(out) + "\n")


def gen_lua():
    hooks = load("hooks")
    ui = load("ui_text")
    sp = load("spfl_structs")
    out = ["-- GENERATED by tools/gen.py from sheets/*.json - edit the sheets, not this file.", "local G = {}", "G.text = {"]
    for r in ui:
        txt = r["text"].replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
        out.append(f'    {r["id"]} = "{txt}",')
    out.append("}")
    out.append("G.off = {")
    for r in sp:
        out.append(f'    {r["field"]} = {r["offset"]},  -- {r["struct"]}: {r["meaning"]}')
    out.append("}")
    out.append("G.exes = {  -- PE link timestamp of the game exe -> game and edit block owner ([[global]+0x48])")
    for r in load("game_exes"):
        out.append(f'    [{r["pe_timestamp"]}] = {{ game = "{r["game"]}", owner_global = {r["owner_global"]} }},'
                   f'  -- {r["exe"]} {r["version"].split(" (")[0]}')
    out.append("}")
    out.append("G.hooks = {")
    for r in hooks:
        if r["game"] == "spfl26":
            out.append(f'    {r["id"]} = {{ event = "{r["event"]}", enabled = {str(r["implemented"]).lower()} }},')
    out.append("}")
    block = "\n".join(out[1:])
    p = os.path.join(ROOT, "spfl", "modules", "matchday.lua")
    src = open(p, encoding="utf-8").read()
    start = src.index("-- BEGIN GENERATED")
    end = src.index("-- END GENERATED")
    first_nl = src.index("\n", start) + 1
    src = src[:first_nl] + block + "\n" + src[end:]
    open(p, "w", encoding="utf-8", newline="\n").write(src)


if __name__ == "__main__":
    gen_python()
    gen_lua()
    print("generated bridge/gen_structs.py and the table in spfl/modules/matchday.lua")
